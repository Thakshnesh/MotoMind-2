from pydantic import BaseModel, Field, ConfigDict
from typing import Optional, List, Dict, Any
from datetime import datetime, timezone

def utc_now():
    return datetime.now(timezone.utc)

class TelemetryDataPoint(BaseModel):
    timestamp: datetime = Field(default_factory=utc_now)
    vehicle_id: str = Field("E2W-SCOOT-01", description="Unique vehicle ID e.g. E2W-SCOOT-01 or E4W-SEDAN-01")
    vehicle_type: str = Field("two_wheeler", description="Vehicle category: two_wheeler or four_wheeler")
    battery_voltage: float = Field(..., description="Pack voltage in Volts")
    battery_current: float = Field(..., description="Pack current in Amps (positive=discharge, negative=charge)")
    battery_temperature: float = Field(..., description="Pack temperature in °C")
    state_of_charge: float = Field(..., description="State of Charge percentage (0-100%)")
    state_of_health: Optional[float] = Field(None, description="State of Health percentage (0-100%)")
    motor_temperature: float = Field(..., description="Primary / Front motor temperature in °C")
    secondary_motor_temperature: Optional[float] = Field(None, description="Secondary / Rear motor temperature in °C (4W)")
    coolant_temperature: Optional[float] = Field(None, description="Coolant loop temperature in °C (Liquid cooled 4W)")
    cabin_temperature: Optional[float] = Field(None, description="HVAC cabin temperature in °C (4W)")
    hvac_power_kw: Optional[float] = Field(None, description="Cabin HVAC power draw in kW (4W)")
    insulation_resistance_kohm: Optional[float] = Field(None, description="HV insulation resistance in kOhm (4W)")
    vehicle_speed: float = Field(..., description="Speed in km/h")
    energy_consumption: float = Field(..., description="Energy consumption in Wh/km")
    charging_status: str = Field("idle", description="idle, discharging, charging, fast_charging")
    ambient_temperature: float = Field(28.0, description="Ambient temperature in °C")
    moisture_status: str = Field("dry", description="dry, damp, wet (2W chassis/flood)")
    sensor_fault_status: bool = Field(False, description="True if sensor fault detected")
    fault_codes: List[str] = Field(default_factory=list, description="Simulated DTC / fault codes")
    power_kw: float = Field(0.0, description="Calculated electrical power in kW")
    temp_delta: float = Field(0.0, description="Battery temp minus ambient temp")
    data_source_type: str = Field("simulated", description="simulated, estimated, measured, or unavailable")
    sensor_availability: Dict[str, str] = Field(default_factory=dict, description="Per-sensor source labeling")
    operating_context: str = Field("normal_cruising", description="Contextual driving state")
    service_mode_active: bool = Field(False, description="Whether vehicle is under service")

class TelemetryResponse(TelemetryDataPoint):
    id: Optional[int] = None
    model_config = ConfigDict(from_attributes=True)

class SimulatorStatus(BaseModel):
    is_running: bool
    active_vehicle_id: str
    active_vehicle_type: str
    current_profile: str
    active_injected_fault: Optional[str] = None
    tick_count: int
    service_mode_active: bool
    latest_telemetry: Optional[TelemetryResponse] = None
    data_source_indicator: str = "SYNTHETIC_SIMULATION"
    available_vehicles: List[Dict[str, Any]] = Field(default_factory=list)
    disclaimer: str = "All values are generated by MotoMind Synthetic EV Physics Simulator for prototype testing."

class FaultInjectionRequest(BaseModel):
    vehicle_id: Optional[str] = None
    fault_type: str = Field(..., description="over_temp_battery, motor_overheat, sudden_voltage_sag, high_discharge_current, moisture_detected, sensor_drift, sensor_disconnect, cell_imbalance, coolant_pump_failure, secondary_motor_overheat, insulation_loss")
    duration_seconds: int = Field(30, description="Duration in seconds before returning to normal profile")

class SimulationProfileRequest(BaseModel):
    vehicle_id: Optional[str] = None
    profile_name: str = Field(..., description="city_commute, aggressive_sport, eco_cruising, idle_charging, dc_fast_charging")

class VehicleSwitchRequest(BaseModel):
    vehicle_id: str = Field(..., description="Vehicle ID to activate: e.g. E2W-SCOOT-01 or E4W-SEDAN-01")
